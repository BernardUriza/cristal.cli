import type { StateCreator } from "zustand";
import type { GameMode, Locomotion } from "../types";
import type { SymbolicArchetype } from "../../shared/archetype";
import type { SymbolicEvent } from "../symbolicBus";
import type { FunnelState, FunnelStep } from "../funnel";
import type { CellCoord } from "../mazeGraph";
import type { DiscoveryKind, DiscoveryState } from "../DiscoveryClock";
import type { WorldInscription } from "../inscriptions/WorldInscriptions";
import type { Room } from "../roomApi";
import type { FalseDoorAnnotation } from "../FalseDoorConsequences";
import type { EmotionalHistoryEntry } from "../EmotionalHistory";
import type { PressureEndingState } from "../PressureEnding";
import type { Stance } from "../../terminal/psych/StanceClassifier";
import type { RuntimeTransferenceSnapshot } from "../RuntimeTransference";
import type { VerticalSliceState } from "../VerticalSlice";

/** where the player stood in the maze on entering a room, restored on leaving */
export interface MazePose {
  pos: [number, number, number];
  yaw: number;
}

export interface SessionSlice {
  /** id of the console the player is currently close enough to interact with */
  nearbyConsoleId: string | null;
  /** id of the ritual glyph the player is currently close enough to invoke */
  nearbyGlyphId: string | null;
  /** index of the room door the player is currently close enough to cross */
  nearbyExit: number | null;
  /** current locomotion clip, mirrored from the Player for the debug HUD */
  locomotion: Locomotion;
  /** player's maze stance, captured on entering a room and restored on leaving */
  mazePose: MazePose | null;
  /** first-five-minutes funnel: seconds since load at which each step was first reached */
  funnel: FunnelState;
  /** modo viaje: pantalla escasa, texto grande, sin parpadeo, el laberinto camina solo si sueltas */
  viaje: boolean;

  /** first time a funnel step is reached this visit it is saved and reported; later calls are no-ops */
  reachFunnel: (step: FunnelStep, now: number) => void;
  setViaje: (on: boolean) => void;
  setNearbyConsole: (consoleId: string | null) => void;
  setNearbyGlyph: (glyphId: string | null) => void;
  setNearbyExit: (index: number | null) => void;
  setLocomotion: (locomotion: Locomotion) => void;
  setMazePose: (pose: MazePose) => void;
}

export interface ConsoleSlice {
  mode: GameMode;
  activeConsoleId: string | null;

  enterConsoleMode: (consoleId: string) => void;
  exitConsoleMode: () => void;
  recordConsoleInput: (input: string) => void;
}

export interface WallsSlice {
  /** the player's own words, written on labyrinth walls */
  inscriptions: WorldInscription[];
  /** seconds-without-a-find meter that feeds starvation relief */
  discovery: DiscoveryState;
  /** a phrase another player archived, waiting to be written deformed on a wall */
  foreignEcho: string | null;

  /** a console phrase lands on a wall near the console it was typed into */
  addInscription: (text: string, stance: Stance | null, originCell: CellCoord, accent: string, now: number) => void;
  noteDiscovery: (kind: DiscoveryKind, key: string, now: number) => void;
  /** a minute without a find: the labyrinth writes a deformed fragment of the player's words ahead */
  relieveStarvation: (playerCell: CellCoord, now: number) => void;
  setForeignEcho: (text: string | null) => void;
  /** ask cristal-api for someone else's phrase, excluding the player's own */
  fetchForeignEcho: () => void;
}

export interface PressureSlice {
  /** most recent symbolic event, surfaced in the debug HUD */
  lastSymbol: SymbolicEvent | null;
  /** room integrity 0-100: decays with time + dread, collapse at 0 */
  stability: number;
  /** psychological pressure 0-1 mirrored from the terminal stance tracker */
  psychologicalPressure: number;
  /** most recent terminal/environment stance mirrored into gameplay */
  psychologicalStance: Stance | null;
  /** short-lived room pressure shock caused by embodied events such as false exits */
  roomPressureSpike: number;
  /** room-linked stance and pressure history */
  emotionalHistory: EmotionalHistoryEntry[];
  /** full-pressure (1.0) surrender sequence; not a failure state */
  pressureEnding: PressureEndingState | null;
  /** D2 pure-model outputs adapted into the live runtime */
  transference: RuntimeTransferenceSnapshot;

  setLastSymbol: (event: SymbolicEvent) => void;
  /** advance the room's integrity decay by dt seconds; collapses at zero */
  tickStability: (dt: number) => void;
  /** mirror terminal stance pressure into gameplay/rendering without a second store */
  setPsychologicalPressure: (pressure: number, stance?: Stance | null) => void;
}

export interface RoomFlowSlice {
  /** room generated by the LLM server on the last glyph invocation / door */
  room: Room | null;
  /** archetype of the active backrooms descent — reused when crossing doors */
  roomArchetype: SymbolicArchetype | null;
  roomLoading: boolean;
  roomError: string | null;
  /** how many rooms have been rewritten this session — feeds generation depth */
  depth: number;
  /** seed of the room the current one was entered from (null at a descent root) */
  parentSeed: number | null;
  /** rooms visited this descent, oldest first — drives the breadcrumb HUD */
  roomHistory: Room[];
  /** recent emotional annotations produced by room traversal */
  falseDoorAnnotations: FalseDoorAnnotation[];
  /** subtle room text surfaced after an avoidance-shaped crossing */
  lastRoomWhisper: string | null;
  /** seeds of rooms that have proven to bite (false door / collapse) */
  dangerousSeeds: number[];
  /** first-playable-run objective and authored consequence tracker */
  verticalSlice: VerticalSliceState;

  /** glyph pressed in the world — opens the first room of a descent */
  invokeGlyph: (archetype: SymbolicArchetype, glyphId: string) => void;
  /** warm the cache for the glyph the rite points at, so the AI room is ready on arrival */
  prefetchGlyphRoom: (archetype: SymbolicArchetype, glyphId: string) => void;
  /** cross exit[index] of the current room — load/generate the next one */
  takeExit: (index: number) => void;
  /** stability hit 0 — mark the room dangerous and expel to the maze */
  collapseRoom: () => void;
  dismissRoom: () => void;
  /** closed rite -> open the next variation; scoped to the slice, keeps terminal memory */
  startNextVariation: () => void;
}

export type GameState = SessionSlice & ConsoleSlice & WallsSlice & PressureSlice & RoomFlowSlice;

export type GameSlice<T> = StateCreator<GameState, [], [], T>;
